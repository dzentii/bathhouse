#!/bin/sh
# Run from backend/. Install pinned tools as documented in README.md first.
set -eu
export GOMAXPROCS="${GOMAXPROCS:-2}"
export GOFLAGS="${GOFLAGS:--p=1}"
tools_dir="${BANYA_TOOLS_DIR:-./bin/tools}"
go build ./...
BANYA_INTEGRATION=0 go test -count=1 ./...
go vet ./...
BANYA_INTEGRATION=0 go test -count=1 -race ./...
"$tools_dir/golangci-lint" run ./...
"$tools_dir/gosec" -quiet -concurrency 2 ./...
if [ "${BANYA_INTEGRATION:-0}" = 1 ]; then
  go test -count=1 -race -timeout 5m -v ./tests/integration
fi
